// Emits the cross-language test vectors both implementations must agree on.
// Every value is deterministic: fixed seeds, fixed nonces, no clock.
import { writeFileSync } from "node:fs";
import {
  addressOf,
  buildCall,
  buildResult,
  callTranscript,
  hex,
  identityFromSeed,
  openCall,
  openResult,
  requestTranscript,
  resultTranscript,
  signRequest,
  signResult,
  signCall,
  unb64u,
  b64u,
  sha256Hex,
} from "../shared/protocol.ts";

const fill = (byte: number, length = 32) => new Uint8Array(length).fill(byte);

const issuer = identityFromSeed(fill(1));
const device = identityFromSeed(fill(3));
const issuerAddress = addressOf(issuer);
const deviceAddress = addressOf(device);

const callId = "11111111-1111-4111-8111-111111111111";
const issuedAt = 1_700_000_000;
const expiresAt = 1_700_000_300;

const callPlaintext = JSON.stringify({ name: "shell", args: '{"command":"uname -a"}' });
const call = buildCall({
  seed: issuer.seed,
  issuer: issuerAddress,
  device: deviceAddress,
  callId,
  name: "shell",
  args: '{"command":"uname -a"}',
  issuedAt,
  expiresAt,
  nonce: fill(9, 24),
  contentKey: fill(7),
  iv: fill(8, 12),
  ephemeralSecret: fill(6),
});
const openedCall = openCall({ seed: device.seed, call });
if (JSON.stringify(openedCall) !== callPlaintext) throw new Error("call seal round trip failed");

const resultPlaintext = '{"ok":true,"output":{"text":"hello eXe"}}';
const result = buildResult({
  seed: device.seed,
  call,
  ok: true,
  plaintext: resultPlaintext,
  issuedAt: issuedAt + 10,
  nonce: fill(12, 24),
  contentKey: fill(10),
  iv: fill(11, 12),
  ephemeralSecret: fill(5),
});
const openedResult = openResult({ seed: issuer.seed, call, result });
if (openedResult !== resultPlaintext) throw new Error("result seal round trip failed");

const request = {
  method: "POST",
  path: `/v1/agents/${deviceAddress}/calls/${callId}/result`,
  address: deviceAddress,
  timestamp: issuedAt,
  nonce: b64u(fill(13, 16)),
};
const vectors = {
  note: "Generated by scripts/vectors.ts. Both eXe implementations must reproduce every digest and signature.",
  keys: {
    issuer_seed: hex(issuer.seed),
    issuer_address: issuerAddress,
    device_seed: hex(device.seed),
    device_address: deviceAddress,
  },
  call: {
    call_id: call.call_id,
    issuer: call.issuer,
    device: call.device,
    issued_at: call.issued_at,
    expires_at: call.expires_at,
    plaintext: callPlaintext,
    sealed: call.sealed,
    transcript_sha256: sha256Hex(callTranscript(call)),
    sig: call.sig,
  },
  result: {
    call_id: result.call_id,
    device: result.device,
    ok: result.ok,
    issued_at: result.issued_at,
    plaintext: resultPlaintext,
    sealed: result.sealed,
    transcript_sha256: sha256Hex(resultTranscript(result)),
    sig: result.sig,
  },
  request: {
    ...request,
    transcript_sha256: sha256Hex(requestTranscript(request)),
    sig: signRequest(device.seed, request),
  },
};

// Belt and braces: the vectors must be self-consistent before they are written.
if (!vectors.call.sig || vectors.call.sig !== signCall(issuer.seed, call)) throw new Error("call signature drift");
if (vectors.result.sig !== signResult(device.seed, result)) throw new Error("result signature drift");
if (unb64u(call.sealed).length !== 24 + 32 + 48 + 12 + unb64u(call.sealed).length - 116) throw new Error("sealed layout drift");

writeFileSync(new URL("../tests/vectors.json", import.meta.url), `${JSON.stringify(vectors, null, 2)}\n`);
console.log(JSON.stringify({ issuer: issuerAddress, device: deviceAddress, call: call.sig.slice(0, 12) }));
