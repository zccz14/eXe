// Emits the cross-language test vectors both implementations must agree on.
import { writeFileSync } from "node:fs";
import {
  accountTranscript,
  approvalTranscript,
  b64u,
  callTranscript,
  hex,
  openCall,
  openResult,
  resultTranscript,
  sealCall,
  sealResult,
  shortAuthenticationString,
  signAccount,
  signApproval,
  signResult,
  unb64u,
} from "../shared/protocol.ts";
import { ed25519, x25519 } from "@noble/curves/ed25519.js";
import { sha256 } from "@noble/hashes/sha2.js";

const seed = (n: number) => new Uint8Array(32).fill(n);
const accountSigSeed = seed(1);
const accountKexSeed = seed(2);
const deviceSigSeed = seed(3);
const deviceKexSeed = seed(4);
const ephemeralSeed = seed(5);
const callEphemeralSeed = seed(6);

const accountSigPub = b64u(ed25519.getPublicKey(accountSigSeed));
const accountKexPub = b64u(x25519.getPublicKey(accountKexSeed));
const deviceSigPub = b64u(ed25519.getPublicKey(deviceSigSeed));
const deviceKexPub = b64u(x25519.getPublicKey(deviceKexSeed));

const ids = {
  callId: "11111111-1111-4111-8111-111111111111",
  deviceId: "22222222-2222-4222-8222-222222222222",
  accountId: "33333333-3333-4333-8333-333333333333",
  pairingId: "44444444-4444-4444-8444-444444444444",
};
const issuedAt = 1_700_000_000;
const expiresAt = 1_700_000_300;

const accountFields = { userId: ids.accountId, nonce: "account-nonce-000000000000", sigPub: accountSigPub, kexPub: accountKexPub, issuedAt };
const approvalFields = {
  pairingId: ids.pairingId,
  deviceId: ids.deviceId,
  accountId: ids.accountId,
  accountSigPub,
  accountKexPub,
  deviceSigPub,
  deviceKexPub,
  issuedAt,
};

// --- upstream: the command is sealed to the device, the cloud sees only the envelope ---
const callPlaintext = JSON.stringify({ name: "echo", args: '{"text":"hello eXe"}' });
const sealedCall = sealCall({
  callId: ids.callId,
  deviceId: ids.deviceId,
  accountId: ids.accountId,
  name: "echo",
  args: '{"text":"hello eXe"}',
  issuedAt,
  expiresAt,
  deviceKexPub: unb64u(deviceKexPub),
  accountSigSeed,
  ephemeralSecret: callEphemeralSeed,
});
const callFields = {
  callId: ids.callId,
  deviceId: ids.deviceId,
  accountId: ids.accountId,
  eph: unb64u(sealedCall.eph),
  nonce: unb64u(sealedCall.nonce),
  ciphertext: unb64u(sealedCall.ct),
  issuedAt,
  expiresAt,
};
const openedCall = openCall({
  deviceKexSk: deviceKexSeed,
  callId: ids.callId,
  deviceId: ids.deviceId,
  accountId: ids.accountId,
  eph: callFields.eph,
  nonce: callFields.nonce,
  ciphertext: callFields.ciphertext,
});
if (JSON.stringify(openedCall) !== callPlaintext) throw new Error("call seal round trip failed");

// --- downstream: the result is sealed to the account ---
const resultPlaintext = '{"ok":true,"output":{"text":"hello eXe"}}';
const sealedResult = sealResult({
  callId: ids.callId,
  deviceId: ids.deviceId,
  ok: true,
  accountKexPub: unb64u(accountKexPub),
  plaintext: resultPlaintext,
  ephemeralSecret: ephemeralSeed,
});
const openedResult = openResult({
  accountKexSk: accountKexSeed,
  callId: ids.callId,
  deviceId: ids.deviceId,
  envelope: sealedResult,
});
if (openedResult !== resultPlaintext) throw new Error("result seal round trip failed");

const resultFields = {
  callId: ids.callId,
  deviceId: ids.deviceId,
  ok: true,
  eph: unb64u(sealedResult.eph),
  nonce: unb64u(sealedResult.nonce),
  ciphertext: unb64u(sealedResult.ct),
};

const vectors = {
  note: "Generated by scripts/vectors.ts. Both eXe implementations must reproduce every digest.",
  keys: {
    account_sig_seed: hex(accountSigSeed),
    account_sig_pub: accountSigPub,
    account_kex_seed: hex(accountKexSeed),
    account_kex_pub: accountKexPub,
    device_sig_seed: hex(deviceSigSeed),
    device_sig_pub: deviceSigPub,
    device_kex_seed: hex(deviceKexSeed),
    device_kex_pub: deviceKexPub,
    call_ephemeral_seed: hex(callEphemeralSeed),
    result_ephemeral_seed: hex(ephemeralSeed),
  },
  account: { ...accountFields, transcript_sha256: hex(sha256(accountTranscript(accountFields))), sig: signAccount(accountSigSeed, accountFields) },
  approval: { ...approvalFields, transcript_sha256: hex(sha256(approvalTranscript(approvalFields))), sig: signApproval(accountSigSeed, approvalFields) },
  call: {
    callId: ids.callId,
    deviceId: ids.deviceId,
    accountId: ids.accountId,
    eph: sealedCall.eph,
    nonce: sealedCall.nonce,
    ct: sealedCall.ct,
    issuedAt,
    expiresAt,
    plaintext: callPlaintext,
    ct_sha256: hex(sha256(callFields.ciphertext)),
    transcript_sha256: hex(sha256(callTranscript(callFields))),
    sig: sealedCall.sig,
  },
  result: {
    call_id: ids.callId,
    device_id: ids.deviceId,
    ok: true,
    plaintext: resultPlaintext,
    eph: sealedResult.eph,
    nonce: sealedResult.nonce,
    ct: sealedResult.ct,
    ct_sha256: hex(sha256(resultFields.ciphertext)),
    transcript_sha256: hex(sha256(resultTranscript(resultFields))),
    sig: signResult(deviceSigSeed, resultFields),
  },
  sas: shortAuthenticationString(accountSigPub, deviceSigPub),
};
writeFileSync(new URL("../tests/vectors.json", import.meta.url), `${JSON.stringify(vectors, null, 2)}\n`);
console.log(JSON.stringify({ sas: vectors.sas, call_ct: vectors.call.ct.slice(0, 12) }));
